declare(strict_types=1);

namespace OCA\OpenRegister\Files\Db;

use OCP\AppFramework\Db\Entity;
use OCP\AppFramework\Db\QBMapper;
use OCP\DB\QueryBuilder\IQueryBuilder;
use OCP\IDBConnection;

/**
 * Reads and writes the text disclosure records.
 *
 * @method TextDisclosure insert(Entity $entity)
 * @method list<TextDisclosure> findEntities(IQueryBuilder $query)
 *
 * @template-extends QBMapper<TextDisclosure>
 *
 * @spec openspec/changes/anonymisation-discloses-itself-pipeline/specs/anonymisation-disclosure/spec.md#requirement-every-external-call-that-carries-a-documents-text-is-recorded-per-document-req-adi-005
 */
class TextDisclosureMapper extends QBMapper {
	/**
	 * Constructor.
	 *
	 * @param IDBConnection $db Database connection.
	 */
	public function __construct(IDBConnection $db) {
		parent::__construct(db: $db, tableName: 'openregister_text_disclosures', entityClass: TextDisclosure::class);
	}//end __construct()

	/**
	 * The disclosures of one file, newest first.
	 *
	 * @param int $fileId The Nextcloud file id.
	 *
	 * @return list<TextDisclosure>
	 *
	 * @spec openspec/changes/anonymisation-discloses-itself-pipeline/specs/anonymisation-disclosure/spec.md#requirement-every-external-call-that-carries-a-documents-text-is-recorded-per-document-req-adi-005
	 */
	public function findByFileId(int $fileId): array {
		$qb = $this->db->getQueryBuilder();

		$qb->select('*')
			->from($this->getTableName())
			->where($qb->expr()->eq('file_id', $qb->createNamedParameter($fileId, IQueryBuilder::PARAM_INT)))
			->orderBy('at', 'DESC')
			->addOrderBy('id', 'DESC');

		return $this->findEntities(query: $qb);
	}//end findByFileId()
}//end class
