declare(strict_types=1);

namespace OCA\OpenRegister\Service\File;

use RuntimeException;

/**
 * A published file whose bytes no longer match the digest sealed at publication.
 *
 * @spec openspec/changes/published-file-digest/specs/file-actions/spec.md#requirement-a-published-file-is-checked-against-its-digest-when-it-is-read-req-pfd-002
 */
class PublishedFileChangedException extends RuntimeException {

	/**
	 * Constructor.
	 *
	 * @param int $fileId The file.
	 *
	 * @spec openspec/changes/published-file-digest/specs/file-actions/spec.md#requirement-a-published-file-is-checked-against-its-digest-when-it-is-read-req-pfd-002
	 */
	public function __construct(public readonly int $fileId) {
		parent::__construct(message: sprintf('Published file %d changed after it was published and is not served.', $fileId));
	}//end __construct()
}//end class
