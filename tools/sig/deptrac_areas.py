"""Write tools/sig/deptrac/areas.yaml from the functional areas in sigrid.components.yaml.

    python3 tools/sig/deptrac_areas.py           # write the config
    python3 tools/sig/deptrac_areas.py --check   # exit 1 when the config is stale

Every `components:` entry becomes a deptrac layer with one directory collector per include
pattern. A pattern `.*/lib/Db/(A|B)[.]php` is matched by Sigrid against the full path; deptrac
matches its collector anywhere in the path, so the leading `.*/` is dropped and a `$` is added.
The ruleset lets every area use Kernel and nothing else, so each reference from one area into
another is reported as a violation.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import check_sig_maintainability as tool  # noqa: E402

SOURCE = os.path.join(REPO, "sigrid.components.yaml")
TARGET = os.path.join(HERE, "deptrac", "areas.yaml")
SHARED = "Kernel"

HEADER = """\
# SPDX-FileCopyrightText: 2026 Conduction <info@conduction.nl>
# SPDX-License-Identifier: EUPL-1.2
#
# GENERATED by tools/sig/deptrac_areas.py from sigrid.components.yaml. Do not edit by hand.
#
# The functional areas of lib/ as deptrac layers. Every area may use Kernel; any other reference
# from one area into another is a violation. Run through tools/sig/deptrac.sh areas.
"""


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def render():
    os.environ["SIG_COMPONENTS_YAML"] = SOURCE
    comps = tool.pattern_components(REPO)
    if not comps:
        raise SystemExit(f"no components: block in {SOURCE}")
    out = [HEADER + "deptrac:", "  paths:", "    - ./lib", "  exclude_files:", "    - '#/lib/Migration/#'", "  layers:"]
    for name, include, _exclude in comps:
        out += [f"    - name: {name}", "      collectors:"]
        for pattern in include:
            value = pattern.pattern[3:] if pattern.pattern.startswith(".*/") else pattern.pattern
            out += ["        - type: directory", f"          value: {quote(value + '$')}"]
    out.append("  ruleset:")
    for name, _include, _exclude in comps:
        out.append(f"    {name}: ~" if name == SHARED else f"    {name}:\n      - {SHARED}")
    return "\n".join(out) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""
        if current != text:
            print(f"{os.path.relpath(TARGET, REPO)} is stale: run python3 tools/sig/deptrac_areas.py")
            return 1
        return 0
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
