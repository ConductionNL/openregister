"""Write tools/sig/deptrac/areas.yaml from the functional areas in sigrid.components.yaml.

    python3 tools/sig/deptrac_areas.py           # write the config
    python3 tools/sig/deptrac_areas.py --check   # exit 1 when the config is stale

Every `components:` entry becomes a deptrac layer with one directory collector per include
pattern. A pattern `.*/lib/Db/(A|B)[.]php` is matched by Sigrid against the full path; deptrac
matches its collector anywhere in the path, so the leading `.*/` is dropped and a `$` is added.
The ruleset lets each area use the areas below it in tools/sig/area-order.json, so each reference
against that order is reported as a violation. An area with exclude patterns gets a bool collector
(its includes, minus its excludes).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import check_sig_maintainability as tool  # noqa: E402

SOURCE = os.path.join(REPO, "sigrid.components.yaml")
TARGET = os.path.join(HERE, "deptrac", "areas.yaml")

HEADER = """\
# SPDX-FileCopyrightText: 2026 Conduction <info@conduction.nl>
# SPDX-License-Identifier: EUPL-1.2
#
# GENERATED by tools/sig/deptrac_areas.py from sigrid.components.yaml. Do not edit by hand.
#
# The functional areas of lib/ as deptrac layers. An area may use the areas below it in
# tools/sig/area-order.json (hydra ADR-119 Decision 8); any other reference from one area into
# another is a violation. Run through tools/sig/deptrac.sh areas.
"""


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def read_order():
    with open(os.path.join(HERE, "area-order.json"), encoding="utf-8") as fh:
        return json.load(fh)["order"]


def collector(pattern):
    value = pattern.pattern[3:] if pattern.pattern.startswith(".*/") else pattern.pattern
    return {"type": "directory", "value": value + "$"}


def render():
    os.environ["SIG_COMPONENTS_YAML"] = SOURCE
    comps = tool.pattern_components(REPO)
    if not comps:
        raise SystemExit(f"no components: block in {SOURCE}")
    out = [HEADER + "deptrac:", "  paths:", "    - ./lib", "  exclude_files:", "    - '#/lib/Migration/#'", "  layers:"]
    for name, include, exclude in comps:
        out += [f"    - name: {name}", "      collectors:"]
        if exclude:
            out += ["        - type: bool", "          must:"]
            for p in include:
                out += ["            - type: directory", f"              value: {quote(collector(p)['value'])}"]
            out.append("          must_not:")
            for p in exclude:
                out += ["            - type: directory", f"              value: {quote(collector(p)['value'])}"]
            continue
        for p in include:
            out += ["        - type: directory", f"          value: {quote(collector(p)['value'])}"]
    order = read_order()
    names = [name for name, _i, _e in comps]
    missing = sorted(set(names) - set(order))
    if missing:
        raise SystemExit(f"areas missing from tools/sig/area-order.json: {missing}")
    out.append("  ruleset:")
    for name in names:
        below = order[:order.index(name)]
        out.append(f"    {name}: ~" if not below else f"    {name}:\n" + "\n".join(f"      - {b}" for b in below))
    return "\n".join(out) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""
        if current != text:
            print(f"{os.path.relpath(TARGET, REPO)} is stale: run python3 tools/sig/deptrac_areas.py")
            return 1
        return 0
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
