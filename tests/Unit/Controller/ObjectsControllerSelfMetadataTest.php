declare(strict_types=1);

namespace OCA\OpenRegister\Tests\Unit\Controller;

use OCA\OpenRegister\Controller\ObjectsController;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use ReflectionMethod;

/**
 * @covers \OCA\OpenRegister\Controller\ObjectsController
 */
class ObjectsControllerSelfMetadataTest extends TestCase {

	/**
	 * Run the object body through the controller's @self filter.
	 *
	 * @param array<string, mixed> $data The body.
	 *
	 * @return array<string, mixed> The filtered body.
	 */
	private function sanitised(array $data): array {
		$controller = (new ReflectionClass(ObjectsController::class))->newInstanceWithoutConstructor();
		return (new ReflectionMethod(ObjectsController::class, 'sanitiseSelfMetadata'))->invoke($controller, $data);
	}

	public function testTheCreateMarkerIsDropped(): void {
		$data = $this->sanitised(['name' => 'x', '@self' => ['_autoGeneratedUuid' => true, 'slug' => 'kept']]);

		$this->assertSame(['slug' => 'kept'], $data['@self']);
		$this->assertSame('x', $data['name']);
	}
}
