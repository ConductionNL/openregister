/**
 * The C10 classes in lib/Service are reached through their interfaces.
 *
 * Each class listed here was named directly by a lib file in another component
 * (lib/AppHost, lib/Reference, lib/Twig). It now has an interface next to it;
 * outside callers type against and resolve that interface, and ContractBindings
 * aliases it to the class, so every caller still gets the one shared instance.
 * A missing alias is a runtime 500 that no other unit test sees, so this test
 * pins the binding as well as the implementation and the callers.
 *
 * @category Test
 * @package  OCA\OpenRegister\Tests\Unit\Architecture
