 *
 * FlowMessagingService built its default OptOutAuthority with new. It now calls
 * OptOutAuthorityFactory::create(), which returns the same object typed as
 * OptOutAuthorityInterface, so no file outside the Notifications component names
 * the concrete class.
 *
 * @category Test
 * @package  OCA\OpenRegister\Tests\Unit\Architecture
