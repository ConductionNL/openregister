<?php

/**
 * Rewrites the reserved-word snapshots from the upstream MariaDB and MySQL sources.
 *
 * ReservedColumnNamesTest merges these files into the lists it reads from
 * upstream, and uses them alone when the download fails. A word upstream stops
 * reserving therefore stays checked until the files are regenerated. Run this
 * when the series in ReservedWordSource::SOURCES change, and now and then so
 * the snapshots follow the upstream branches:
 *
 *   php tests/Unit/Migration/fixtures/update-reserved-words.php
 *
 * It needs network and writes one file per engine and series; commit the result.
 *
 * SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>
 * SPDX-License-Identifier: EUPL-1.2
 */

declare(strict_types=1);

require_once __DIR__.'/../../../Support/ReservedWordSource.php';

use OCA\OpenRegister\Tests\Support\ReservedWordSource;

$status = 0;
foreach (ReservedWordSource::SOURCES as $engine => $source) {
	foreach ($source['series'] as $series) {
		$words = ReservedWordSource::fetch(engine: $engine, series: $series);
		if ($words === null) {
			fwrite(STDERR, 'Could not download the '.$engine.' '.$series.' sources: '.(ReservedWordSource::downloadFailure() ?? 'unknown reason').PHP_EOL);
			$status = 1;
			continue;
		}

		$header = [
			'# SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>',
			'# SPDX-License-Identifier: EUPL-1.2',
			'#',
			'# Words '.$engine.' '.$series.' refuses as an unquoted column name: the keywords in',
			'# '.ReservedWordSource::url(engine: $engine, series: $series, file: 'sql/lex.h'),
			'# that '.$source['identifier'].' in',
			'# '.ReservedWordSource::url(engine: $engine, series: $series, file: 'sql/sql_yacc.yy'),
			'# does not allow as an identifier. Snapshot of '.gmdate('Y-m-d').'.',
			'# Generated by update-reserved-words.php; do not edit by hand.',
			'# ReservedColumnNamesTest always merges this list with the live one, so a word',
			'# upstream stops reserving stays here until this file is regenerated.',
		];

		$path = ReservedWordSource::snapshotPath(engine: $engine, series: $series);
		file_put_contents($path, implode("\n", array_merge($header, $words))."\n");
		echo $engine.' '.$series.': '.count($words).' words'.PHP_EOL;
	}
}

exit($status);
