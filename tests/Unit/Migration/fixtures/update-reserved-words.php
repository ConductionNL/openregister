<?php

/**
 * Rewrites the reserved-word snapshots from the upstream MariaDB and MySQL sources.
 *
 * ReservedColumnNamesTest merges these files into the lists it reads from the
 * upstream branch heads, and uses them alone when the download fails. A branch
 * head is only the newest point release, and upstream also un-reserves words,
 * so a released series' snapshot is the union over the head and every release
 * tag of that series (`mariadb-10.6.0` to `mariadb-10.6.28`, `mysql-8.0.0` ...);
 * it is the only place the older point releases are checked. A development
 * branch (`main`, `trunk`) has no tags: head only. A word upstream stops
 * reserving stays in a snapshot until the files are regenerated. Run this when
 * the series in ReservedWordSource::SOURCES change, and now and then so the
 * snapshots follow new point releases:
 *
 *   GITHUB_TOKEN=<token> php tests/Unit/Migration/fixtures/update-reserved-words.php
 *
 * It needs network, downloads two source files per tag (about 200 tags, a few
 * minutes) and writes one file per engine and series; commit the result.
 * GITHUB_TOKEN is optional and only lifts GitHub's anonymous rate limit; the
 * script goes one request at a time and, when a limit or an outage stops it,
 * names the cause and exits 1. Finished tags are cached (RESERVED_WORDS_CACHE,
 * default a folder in the system temp directory), so running it again resumes.
 *
 * SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>
 * SPDX-License-Identifier: EUPL-1.2
 */

declare(strict_types=1);

require_once __DIR__.'/../../../Support/ReservedWordSource.php';

use OCA\OpenRegister\Tests\Support\ReservedWordSource;

$status = 0;
foreach (ReservedWordSource::SOURCES as $engine => $source) {
	foreach ($source['series'] as $series) {
		try {
			$words = ReservedWordSource::fetch(engine: $engine, series: $series);
			if ($words === null) {
				throw new RuntimeException('Could not download the '.$engine.' '.$series.' sources: '.(ReservedWordSource::downloadFailure() ?? 'unknown reason'));
			}

			$tags = [];
			if (ReservedWordSource::isDevelopment(engine: $engine, series: $series) === false) {
				$tags = ReservedWordSource::releaseTags(engine: $engine, series: $series);
				foreach ($tags as $tag) {
					fwrite(STDERR, $engine.' '.$series.': '.$tag.PHP_EOL);
					$words = array_merge($words, ReservedWordSource::releaseWords(engine: $engine, tag: $tag));
				}
			}
		} catch (RuntimeException $exception) {
			fwrite(STDERR, $exception->getMessage().PHP_EOL);
			$status = 1;
			continue;
		}

		$words = array_values(array_unique($words));
		sort($words);

		$covered = ($tags === [])
			? 'the head of branch '.$series.' only (a development branch has no release tags)'
			: 'the head of branch '.$series.' and every release tag '.$tags[0].' to '.end($tags).' ('.count($tags).' tags)';

		$header = [
			'# SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>',
			'# SPDX-License-Identifier: EUPL-1.2',
			'#',
			'# Words '.$engine.' '.$series.' refuses as an unquoted column name: the keywords in',
			'# '.ReservedWordSource::url(engine: $engine, series: $series, file: 'sql/lex.h'),
			'# that '.$source['identifier'].' in',
			'# '.ReservedWordSource::url(engine: $engine, series: $series, file: 'sql/sql_yacc.yy'),
			'# does not allow as an identifier, unioned over',
			'# '.$covered.'.',
			'# Snapshot of '.gmdate('Y-m-d').'; releases after that day are not in it.',
			'# Generated by update-reserved-words.php; do not edit by hand.',
			'# ReservedColumnNamesTest always merges this list with the live branch head, so a word',
			'# upstream stops reserving stays here until this file is regenerated.',
		];

		$path = ReservedWordSource::snapshotPath(engine: $engine, series: $series);
		file_put_contents($path, implode("\n", array_merge($header, $words))."\n");
		echo $engine.' '.$series.': '.count($words).' words'.(($tags === []) ? '' : ' from '.count($tags).' tags and the head').PHP_EOL;
	}
}

exit($status);
