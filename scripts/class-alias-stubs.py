"""Generate tests/stubs/ClassAliases.php from appinfo/class-aliases.json.

Psalm reads the old names of moved classes from this stub: it does not run the
lazy autoloader that lib/AppInfo/ClassAliasMap.php registers. phpunit and phpstan
apply the map itself (tests/bootstrap*.php, phpstan-bootstrap.php).

A moved interface is declared under its old name as an empty interface that
extends the new one. Psalm 5 does read a literal `class_alias()` call, but it
crashes ("Could not get class storage") on a constant fetched through an aliased
interface name, and an implementer or caller that keeps the old name is exactly
the case this stub exists for. Every other entry (classes, enums) is a literal
`class_alias()` call with two string literals: a final class cannot be extended,
and the `New::class` spelling makes psalm load the target while it reads the
stubs, which surfaced circular-reference errors that the string form does not.

Usage:
    python3 scripts/class-alias-stubs.py           # write the stub
    python3 scripts/class-alias-stubs.py --check   # exit 1 when the stub is stale

tests/Unit/Architecture/ClassAliasStubTest.php fails when the stub and the json
disagree; rerun this script after scripts/component-move.py adds an entry.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP_FILE = ROOT / "appinfo" / "class-aliases.json"
STUB_FILE = ROOT / "tests" / "stubs" / "ClassAliases.php"

HEADER = """<?php

/**
 * ClassAliases: the old names of moved classes, for psalm.
 *
 * GENERATED by scripts/class-alias-stubs.py from appinfo/class-aliases.json.
 * Do not edit; rerun the script. Listed in psalm.xml under <stubs>.
 *
 * SPDX-License-Identifier: EUPL-1.2
 * SPDX-FileCopyrightText: 2026 Conduction B.V.
 *
 * @category Test
 * @package  OCA\\OpenRegister\\Tests
 *
 * @author    Conduction Development Team <info@conduction.nl>
 * @copyright 2026 Conduction B.V.
 * @license   EUPL-1.2 https://joinup.ec.europa.eu/collection/eupl/eupl-text-eupl-12
 *
 * @link https://www.OpenRegister.nl
 */

declare(strict_types=1);

"""


def php_string(name: str) -> str:
    """Return a single-quoted PHP literal of a class name."""
    return "'" + name.replace("\\", "\\\\").replace("'", "\\'") + "'"


KIND = re.compile(r"^\s*(?:(?:final|abstract|readonly)\s+)*(class|interface|trait|enum)\s+\w+", re.M)


def source_file(fqcn: str) -> Path:
    """Return the file PSR-4 maps a class name to (composer.json: OCA\\OpenRegister\\ => lib/)."""
    prefix = "OCA\\OpenRegister\\"
    if not fqcn.startswith(prefix):
        raise SystemExit(f"alias target outside OCA\\OpenRegister: {fqcn}")
    return ROOT / "lib" / (fqcn[len(prefix):].replace("\\", "/") + ".php")


def kind_of(fqcn: str) -> str:
    """Return class, interface, trait or enum for an alias target."""
    path = source_file(fqcn)
    if not path.exists():
        raise SystemExit(f"alias target has no file: {fqcn} ({path.relative_to(ROOT)})")
    match = KIND.search(path.read_text(encoding="utf-8"))
    if match is None:
        raise SystemExit(f"no class-like declaration in {path.relative_to(ROOT)}")
    return match.group(1)


def render(map_file: Path = MAP_FILE) -> str:
    """Render the stub for the given alias map."""
    data = json.loads(map_file.read_text(encoding="utf-8"))
    aliases = data.get("aliases", {})
    interfaces: list[str] = []
    calls: list[str] = []
    for old in sorted(aliases):
        new = aliases[old]["class"]
        if kind_of(new) == "interface":
            namespace, _, short = old.rpartition("\\")
            interfaces.append(
                f"namespace {namespace} {{\n\tinterface {short} extends \\{new} {{\n\t}}\n}}\n"
            )
            continue
        calls.append(f"\tclass_alias({php_string(new)}, {php_string(old)});\n")
    parts = [HEADER] + [block + "\n" for block in interfaces]
    parts.append("namespace {\n" + "".join(calls) + "}\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        current = STUB_FILE.read_text(encoding="utf-8") if STUB_FILE.exists() else ""
        if current != content:
            print(f"{STUB_FILE.relative_to(ROOT)} is stale: run python3 scripts/class-alias-stubs.py", file=sys.stderr)
            return 1
        return 0
    STUB_FILE.write_text(content, encoding="utf-8")
    print(f"wrote {STUB_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
