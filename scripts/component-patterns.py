"""Generate sigrid.components.yaml from scripts/component-map.csv (ADR-012 Rule 1).

The functional components of ADR-012 are defined by file pattern over the
unchanged Nextcloud layout. The `component` column of scripts/component-map.csv
names the component of every PHP file under lib/ (lib/Migration excepted: Sigrid
excludes it). A row whose `file` ends in `/` is a directory row: it covers every
file under that directory, recursively, unless a file row or a deeper directory
row covers the file. A directory row is only correct when the whole directory
belongs to one component; lib/Kernel/, lib/Support/ and lib/Contract/ are such
rows, so a file moved into them needs no row of its own.

The patterns are built the way sig-measure/components.yaml was built:

- Kernel is listed first, then the other components in a fixed order.
- In the flat layer directories (FLAT below) one alternation of class names per
  component and directory: `.*/lib/Db/(Foo|Bar)[.]php`.
- Every other directory whose files share one component is one pattern
  `.*/lib/<dir>/[^/]*`; a directory whose files do not gets one pattern per file.
- lib/Kernel and lib/Support are recursive (`.*/lib/Kernel/.*`), because the
  contract lanes add subdirectories to them (Kernel/Context, Support/Jobs, ...).

Usage:
    python3 scripts/component-patterns.py           # write sigrid.components.yaml
    python3 scripts/component-patterns.py --check   # exit 1 when it is stale or a file has no component

Stale rows (a file that moved away or was deleted) are reported, never fatal, so
lanes that move files do not collide on the csv. A file without a row is fatal:
add a row for it (or a directory row when its whole directory is one component).
tests/Unit/Architecture/ComponentDefinitionTest.php enforces the same rules.
"""

from __future__ import annotations

import csv
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "lib"
MAP_FILE = ROOT / "scripts" / "component-map.csv"
OUT_FILE = ROOT / "sigrid.components.yaml"

# Kernel first, so its patterns are read first; the order of the rest is fixed for a stable diff.
ORDER = ["Kernel", "Core", "Processes", "Configuration", "Compliance", "Integrations", "Files", "Search", "Notifications", "Platform"]

# The Nextcloud layer directories: one alternation of class names per component.
FLAT = {
    "lib/BackgroundJob",
    "lib/BulkAction",
    "lib/Command",
    "lib/Controller",
    "lib/Db",
    "lib/Event",
    "lib/Exception",
    "lib/Listener",
    "lib/Repair",
    "lib/Service",
}

# Matched recursively, so subdirectories the contract lanes add need no new pattern.
RECURSIVE = {"lib/Kernel": "Kernel", "lib/Support": "Kernel"}

# Sigrid excludes migrations by default; they belong to no component.
EXCLUDED = ("lib/Migration/",)

HEADER = """# Functional components of OpenRegister (ADR-012 Rule 1), over the unchanged Nextcloud layout.
#
# GENERATED by scripts/component-patterns.py from the `component` column of
# scripts/component-map.csv. Do not edit by hand: change the csv and rerun the script.
# tests/Unit/Architecture/ComponentDefinitionTest.php fails when this file is stale.
#
# Kernel is listed first. Every PHP file under lib/ (lib/Migration excepted, which
# Sigrid excludes) matches exactly one component; nothing falls in a Remainder.
#
# sigrid.yaml does NOT read this block yet: it switches to it (replacing
# component_base_dirs) when the contract stage of ADR-012/ADR-013 has landed.
components:
"""


def lib_files() -> list[str]:
    """Every PHP file under lib/, as `lib/...`, sorted; lib/Migration excepted."""
    found = []
    for directory, _dirs, files in os.walk(LIB):
        for name in files:
            if name.endswith(".php"):
                rel = os.path.relpath(os.path.join(directory, name), ROOT).replace(os.sep, "/")
                if not rel.startswith(EXCLUDED):
                    found.append(rel)
    return sorted(found)


def read_rows(map_file: Path = MAP_FILE) -> tuple[dict[str, str], dict[str, str]]:
    """Return (file rows, directory rows) as `lib/...` path => component."""
    files: dict[str, str] = {}
    dirs: dict[str, str] = {}
    with open(map_file, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            component = (row.get("component") or "").strip()
            path = "lib/" + row["file"].strip()
            if component == "":
                raise SystemExit(f"{map_file.name}: row {row['file']} has no component")
            if component not in ORDER:
                raise SystemExit(f"{map_file.name}: row {row['file']} names unknown component {component}")
            if path.endswith("/"):
                dirs[path.rstrip("/")] = component
            else:
                files[path] = component
    return files, dirs


def assign(files: list[str], file_rows: dict[str, str], dir_rows: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Return (path => component, paths without a row). A file row wins over the deepest directory row."""
    assigned: dict[str, str] = {}
    missing: list[str] = []
    for path in files:
        if path in file_rows:
            assigned[path] = file_rows[path]
            continue
        directory = os.path.dirname(path)
        while directory not in ("lib", ""):
            if directory in dir_rows:
                assigned[path] = dir_rows[directory]
                break
            directory = os.path.dirname(directory)
        else:
            missing.append(path)
    return assigned, missing


def esc(path: str) -> str:
    """Escape regex metacharacters the way the design did: `.` becomes `[.]`."""
    return re.sub(r"([.\[\]()+?^$])", lambda match: "[" + match.group(1) + "]", path)


def recursive_root(directory: str) -> str | None:
    """The RECURSIVE directory a directory lies in, if any."""
    for root in RECURSIVE:
        if directory == root or directory.startswith(root + "/"):
            return root
    return None


def render(assigned: dict[str, str]) -> str:
    """Render the components block for a complete assignment."""
    by_dir: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for path, component in assigned.items():
        by_dir[os.path.dirname(path)][component].append(path)

    patterns: dict[str, list[str]] = defaultdict(list)
    emitted_roots: set[str] = set()
    for directory in sorted(by_dir):
        components = by_dir[directory]
        root = recursive_root(directory)
        if root is not None:
            if set(components) != {RECURSIVE[root]}:
                stray = sorted(p for c, ps in components.items() if c != RECURSIVE[root] for p in ps)
                raise SystemExit(f"{root} is matched recursively as {RECURSIVE[root]}, but the csv puts these elsewhere: {stray}")
            if root not in emitted_roots:
                patterns[RECURSIVE[root]].append(f".*/{esc(root)}/.*")
                emitted_roots.add(root)
            continue
        if directory in FLAT:
            for component in sorted(components):
                stems = sorted(os.path.basename(path)[:-4] for path in components[component])
                patterns[component].append(f".*/{esc(directory)}/({'|'.join(stems)})[.]php")
            continue
        if len(components) == 1:
            (component,) = components
            patterns[component].append(f".*/{esc(directory)}/[^/]*")
            continue
        for component in sorted(components):
            for path in sorted(components[component]):
                patterns[component].append(f".*/{esc(path)}")

    out = [HEADER]
    for component in ORDER:
        out.append(f"  - name: {component}\n")
        out.append("    include:\n")
        for pattern in patterns[component]:
            out.append(f'      - "{pattern}"\n')
    return "".join(out)


def build() -> tuple[str, list[str], list[str]]:
    """Return (yaml, files without a row, stale rows)."""
    files = lib_files()
    file_rows, dir_rows = read_rows()
    assigned, missing = assign(files, file_rows, dir_rows)
    present = set(files)
    stale = sorted(path for path in file_rows if path not in present and not path.startswith(EXCLUDED))
    stale += sorted(d + "/" for d in dir_rows if not (ROOT / d).is_dir())
    return render(assigned), missing, stale


def main(argv: list[str]) -> int:
    content, missing, stale = build()
    for path in stale:
        print(f"stale row (no such file under lib/; remove the row when convenient): {path[4:]}", file=sys.stderr)
    if missing:
        for path in missing:
            top = path[4:].split("/")[0]
            print(f"no component for {path}: add the row `{path[4:]},,{top},,,,,<component>` to scripts/component-map.csv", file=sys.stderr)
        return 1
    if "--check" in argv:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != content:
            print("sigrid.components.yaml is stale: run python3 scripts/component-patterns.py", file=sys.stderr)
            return 1
        return 0
    OUT_FILE.write_text(content, encoding="utf-8")
    print(f"wrote {OUT_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
